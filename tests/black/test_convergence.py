"""Сходимость численного решения по шагу сетки и числу шагов PEB.

Результат модели не должен зависеть от параметров дискретизации; эти тесты показывают, с какой погрешностью
выбранные по умолчанию сетка 1 × 1 нм и 30 шагов PEB воспроизводят предел мелкой сетки."""
from dataclasses import replace
import numpy as np
import pytest
from lersim.process import Process, simulate, mean_field, _lercore

pytestmark = pytest.mark.skipif(_lercore is None, reason="модуль C++ не собран (на эталонном ядре расчёт занял бы часы)")
P = replace(Process(), L=1200.0)


def run(p, n=16, **kw):
    r = simulate(p, n, "cpp", keep_map=False, **kw)
    w = (r["xR"] - r["xL"]).mean(1)
    ler = 3 * r["sigma_single"]
    return r["m"]["CD"], 0.5 * (r["m"]["LER_L"] + r["m"]["LER_R"]), w.std(ddof=1) / np.sqrt(w.size), ler.std(ddof=1) / np.sqrt(ler.size)


def test_grid_convergence(rec):
    """Ширина и шероховатость сходятся при измельчении сетки.

    Метод: 16 реализаций длиной 1,2 мкм на сетках 1 × 1 нм (по умолчанию) и 0,5 × 0,5 нм; одинаковые
    физические параметры; без шума — ширина по средним концентрациям на сетках 1; 0,5; 0,25 нм.
    Критерий: без шума ширина на сетке 1 нм отличается от сетки 0,25 нм меньше чем на 0,1 нм; со стохастикой
    разность ширин меньше 0,5 нм, разность LER меньше 5 % (статистическая погрешность каждой оценки ≈ 2 %).
    Зачем: результат не должен быть артефактом размера ячейки. Это требует конечного радиуса реакции r_c:
    при точечных молекулах скорость захвата кислоты тушителем зависит от размера ячейки.
    """
    cd = {dx: mean_field(replace(P, dx=dx))[0] for dx in (1.0, 0.5, 0.25)}
    for dx in (1.0, 0.5, 0.25):
        rec(f"Ширина без шума, Δx = {dx:g} нм", cd[dx], "", "нм")
    e = abs(cd[1.0] - cd[0.25])
    assert rec("Ширина без шума: сетка 1 нм − 0,25 нм", e, "< 0,1", "нм", e < 0.1)
    a, b = run(P), run(replace(P, dx=0.5, dy=0.5))
    rec("Сетка 1 × 1 нм: CD; LER", f"{a[0]:.2f}; {a[1]:.3f}", "", "нм")
    rec("Сетка 0,5 × 0,5 нм: CD; LER", f"{b[0]:.2f}; {b[1]:.3f}", "", "нм")
    assert rec("Разность ширин", a[0] - b[0], "|…| < 0,5", "нм", abs(a[0] - b[0]) < 0.5)
    d = abs(a[1] / b[1] - 1)
    assert rec("Относительная разность LER", d, "< 0,05", "", d < 0.05)


def test_time_step_convergence(rec):
    """Ширина и шероховатость сходятся при уменьшении шага PEB.

    Метод: 30 шагов (по умолчанию) и 120 шагов; одни и те же случайные числа экспонирования (общий генератор),
    поэтому разность отражает только ошибку шага.
    Критерий: разность ширин меньше 0,2 нм, относительная разность LER меньше 2 %.
    Зачем: расщепление «диффузия — нейтрализация — депротекция» имеет ошибку порядка шага; её величина должна
    быть мала по сравнению с измеряемыми эффектами.
    """
    a, b = run(P, 8), run(P, 8, n_steps=120)
    rec("30 шагов: CD; LER", f"{a[0]:.3f}; {a[1]:.3f}", "", "нм")
    rec("120 шагов: CD; LER", f"{b[0]:.3f}; {b[1]:.3f}", "", "нм")
    assert rec("Разность ширин", a[0] - b[0], "|…| < 0,2", "нм", abs(a[0] - b[0]) < 0.2)
    d = abs(a[1] / b[1] - 1)
    assert rec("Относительная разность LER", d, "< 0,02", "", d < 0.02)
