def test_left_and_right_edges_statistically_equal(rec, p):
    """Левый и правый края статистически равноправны.

    Метод: 32 повторения; средняя σ левого и правого края.
    Критерий: разность меньше 4 стандартных ошибок.
    Зачем: геометрия симметрична; перекос означал бы ошибку в обходе сетки или проявлении.
    """
    r = simulate(p, 32)
    uL, uR = r["xL"] - r["xL"].mean(1, keepdims=True), r["xR"] - r["xR"].mean(1, keepdims=True)
    sL, sR = np.sqrt((uL**2).mean(1)), np.sqrt((uR**2).mean(1))
    t = 4 * np.hypot(se(sL), se(sR))
    rec("Средняя σ левого края", sL.mean(), "", "нм")
    rec("Средняя σ правого края", sR.mean(), "", "нм")
    assert rec("Разность", sL.mean() - sR.mean(), f"|…| < {t:.3f}", "нм", abs(sL.mean() - sR.mean()) < t)


def test_line_length_changes_precision_not_mean(rec, p):
    """Длина участка влияет на точность, но не на среднюю ширину.

    Метод: участок 0,6 мкм × 12 повторений и 2,4 мкм × 3 повторения (одинаковая общая длина).
    Критерий: разность средних ширин меньше 4 стандартных ошибок + 0,2 нм.
    Зачем: результат не должен зависеть от выбранной длины расчёта, только его погрешность.
    """
    a, b = simulate(p, 12), simulate(replace(p, L=2400.0), 3)
    wa, wb = (a["xR"] - a["xL"]).mean(1), (b["xR"] - b["xL"]).mean(1)
    t = 4 * np.hypot(se(wa), se(wb)) + 0.2
    rec("Средняя ширина, 0,6 мкм", wa.mean(), "", "нм")
    rec("Средняя ширина, 2,4 мкм", wb.mean(), "", "нм")
    assert rec("Разность", wa.mean() - wb.mean(), f"|…| < {t:.2f}", "нм", abs(wa.mean() - wb.mean()) < t)


def test_more_realizations_reduce_uncertainty(rec, p):
    """Больше повторных расчётов — меньше погрешность.

    Метод: стандартная ошибка средней σ края при 4 и 32 повторениях.
    Критерий: при 32 повторениях она меньше.
    Зачем: подтверждает смысл режима Монте-Карло.
    """
    s4, s32 = se(simulate(p, 4)["sigma_single"]), se(simulate(p, 32)["sigma_single"])
    rec("Стандартная ошибка при 4 повторениях", s4, "", "нм")
    assert rec("Стандартная ошибка при 32 повторениях", s32, f"< {s4:.4f}", "нм", s32 < s4)


def test_process_window_consistency(rec, p):
    """Окно процесса согласовано с основным расчётом.

    Метод: полный стохастический расчёт на сетке 7 доз × 7 фокусов с общими случайными числами; энергетическая
    широта EL, доза номинального размера при фокусе 0; проверочный расчёт 8 реализаций с другим генератором
    при найденной дозе.
    Критерий: EL симметрична по фокусу (изображение симметрично относительно Δz = 0) и максимальна при Δz = 0;
    ширина убывает с дозой; в проверочном расчёте ширина отличается от заданной меньше чем на 1 нм.
    Зачем: связывает окно процесса с основным расчётом и проверяет гладкость кривых при общих случайных числах.
    """
    doses, focuses = np.linspace(24, 42, 7), np.linspace(-300, 300, 7)
    CD, LER = window(p, doses, focuses)
    E0, EL, dof = latitude(CD, doses, focuses, p.CD)
    j = focuses.size // 2
    sym = np.allclose(EL, EL[::-1], equal_nan=True)
    assert rec("Энергетическая широта EL симметрична по фокусу", sym, "да", "", sym)
    assert rec("Максимум энергетической широты — при Δz = 0", float(focuses[np.nanargmax(EL)]), "0", "нм", np.nanargmax(EL) == j)
    c = CD[:, j]
    mono = bool(np.all(np.diff(c[np.isfinite(c)]) < 0))
    assert rec("Ширина убывает с дозой при Δz = 0", mono, "да", "", mono)
    rec("Доза номинального размера при фокусе 0", E0[j], "", "мДж/см²")
    cd = simulate(replace(p, dose=E0[j], seed=99), 8)["m"]["CD"]
    assert rec("Ширина при этой дозе (8 реализаций, другой генератор)", cd, f"{p.CD:g} ± 1", "нм", abs(cd - p.CD) < 1.0)
    assert rec("Глубина фокуса DOF", dof, f"0 … {focuses[-1] - focuses[0]:g}", "нм", 0 < dof <= focuses[-1] - focuses[0])


@pytest.mark.skipif(_lercore is None, reason="модуль C++ не собран")
def test_engines_agree(rec, p):
    """Два вычислительных ядра дают одну модель.

    Метод: по 24 повторения ядром C++ и ядром NumPy через общий интерфейс.
    Критерий: средние ширины отличаются меньше чем на 4 стандартные ошибки + 0,3 нм; средние σ — меньше 4 ошибок.
    Зачем: пользователь может выбрать любое ядро; результаты не должны зависеть от выбора.
    """
    a, b = simulate(p, 24, "cpp"), simulate(p, 24, "numpy")
    wa, wb = (a["xR"] - a["xL"]).mean(1), (b["xR"] - b["xL"]).mean(1)
    sa, sb = a["sigma_single"], b["sigma_single"]
    t1, t2 = 4 * np.hypot(se(wa), se(wb)) + 0.3, 4 * np.hypot(se(sa), se(sb))
    assert rec("Разность средних ширин", wa.mean() - wb.mean(), f"|…| < {t1:.2f}", "нм", abs(wa.mean() - wb.mean()) < t1)
    assert rec("Разность средних σ", sa.mean() - sb.mean(), f"|…| < {t2:.3f}", "нм", abs(sa.mean() - sb.mean()) < t2)
