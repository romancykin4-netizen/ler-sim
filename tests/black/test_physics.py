"""Физические закономерности (метаморфические испытания).

Модель рассматривается как неизвестная функция «параметры → результат»; проверяется, как меняется
результат при известном изменении входных данных."""
from dataclasses import replace
import numpy as np
import pytest
from lersim.process import Process, simulate, mean_field, _lercore
from lersim.sweep import window, latitude
from tests.conftest import se, ler

NAMES = {"dose": ("доза", "мДж/см²"), "T_peb": ("температура PEB", "°C"), "t_peb": ("время PEB", "с"),
         "t_dev": ("время проявления", "с"), "CD": ("ширина на маске", "нм"), "L_D": ("длина диффузии", "нм")}


def series(rec, p, key, values, n=2, what="CD"):
    name, unit = NAMES[key]
    out = []
    for v in values:
        r = simulate(replace(p, **{key: v}), n)
        out.append(r["m"]["CD"] if what == "CD" else ler(r))
        rec(f"{'Ширина линии' if what == 'CD' else 'Шероховатость края'} при {name} {v:g} {unit}", out[-1], "", "нм")
    return out


def monotone(seq, up=False):
    return all((b > a) if up else (a > b) for a, b in zip(seq, seq[1:]))


def test_more_dose_narrower_line(rec, p):
    """Ширина линии строго убывает с ростом дозы.

    Метод: доза 24, 28, 32, 36, 40 мДж/см², остальное по умолчанию, 2 повторения на точку.
    Критерий: каждая следующая ширина меньше предыдущей.
    Зачем: в позитивном резисте больше света — больше кислоты — шире пробел и уже линия.
    """
    c = series(rec, p, "dose", [24, 28, 32, 36, 40])
    assert rec("Ширина строго убывает", monotone(c), "да", "", monotone(c))


