def test_focus_sign_does_not_matter(rec, p):
    """Знак расфокусировки не влияет на результат.

    Метод: фокус +120 и −120 нм при одинаковом генераторе.
    Критерий: контуры краёв совпадают побитово.
    Зачем: без аберраций изображение симметрично по фокусу; иначе — ошибка фазы зрачка.
    """
    a, b = simulate(replace(p, focus=120), 2), simulate(replace(p, focus=-120), 2)
    same = np.array_equal(a["xL"], b["xL"]) and np.array_equal(a["xR"], b["xR"])
    assert rec("Контуры при +120 и −120 нм совпадают", same, "да", "", same)


def test_defocus_degrades_contrast_and_roughness(rec, p):
    """Расфокусировка снижает наклон изображения и увеличивает шероховатость.

    Метод: фокус 0 и 150 нм; NILS по одному расчёту, LER по 16 повторениям.
    Критерий: NILS(150) < NILS(0); LER(150) > LER(0).
    Зачем: главный механизм связи оптики и LER — пологий край изображения усиливает шум.
    """
    n0, n1 = simulate(p, 1)["NILS"], simulate(replace(p, focus=150), 1)["NILS"]
    rec("NILS в фокусе", n0)
    assert rec("NILS при расфокусе 150 нм", n1, f"< {n0:.3f}", "", n1 < n0)
    a, b = ler(simulate(p, 16)), ler(simulate(replace(p, focus=150), 16))
    rec("LER в фокусе", a, "", "нм")
    assert rec("LER при расфокусе 150 нм", b, f"> {a:.2f}", "нм", b > a)


def test_optics_trends_in_contrast(rec, p):
    """Наклон изображения растёт с числовой апертурой и падает с длиной волны.

    Метод: NILS при NA 0,65 / 0,75 / 0,85 и при λ 193 и 248 нм.
    Критерий: NILS(0,85) > NILS(0,75) > NILS(0,65); NILS(248) < NILS(193).
    Зачем: разрешение растёт как NA/λ — базовое свойство проекционной оптики.
    """
    v = {k: simulate(replace(p, **k2), 1)["NILS"] for k, k2 in (("0,65", dict(NA=0.65)), ("0,75", {}), ("0,85", dict(NA=0.85)))}
    for k, n in v.items():
        rec(f"NILS при NA {k}", n)
    ok = v["0,85"] > v["0,75"] > v["0,65"]
    assert rec("NILS растёт с апертурой", ok, "да", "", ok)
    n248 = simulate(replace(p, wl=248.0), 1)["NILS"]
    assert rec("NILS при 248 нм", n248, f"< {v['0,75']:.3f} (193 нм)", "", n248 < v["0,75"])


def test_shot_noise_scaling(rec, p):
    """Дробовой шум подчиняется закону σ ∝ 1/√V.

    Метод: эффективная толщина 50 и 200 нм (объём ячейки ×4), по 16 повторений.
    Критерий: отношение LER от 0,40 до 0,62 (теория — 0,5).
    Зачем: количественная проверка того, что шероховатость действительно создаётся статистикой молекул.
    """
    a, b = ler(simulate(replace(p, h_eff=50.0), 16)), ler(simulate(replace(p, h_eff=200.0), 16))
    rec("LER при толщине 50 нм", a, "", "нм")
    rec("LER при толщине 200 нм", b, "", "нм")
    assert rec("Отношение LER", b / a, "0,5 (допуск 0,40 … 0,62)", "", 0.40 < b / a < 0.62)


