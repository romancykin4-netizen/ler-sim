"""Статистическая оценка с интервалами погрешности: квантили, интервалы, величины одной линии (lersim/stats.py)."""
from dataclasses import replace
import numpy as np
from lersim.process import Process
from lersim.stats import norm_ppf, t_cdf, t_ppf, summary, per_line, perturbed

# Табличные квантили распределения Стьюдента, 10 значащих цифр.
T_TABLE = [(1, 0.975, 12.70620474), (2, 0.975, 4.302652730), (3, 0.975, 3.182446305), (3, 0.995, 5.840909310),
           (5, 0.995, 4.032142984), (7, 0.95, 1.894578605), (10, 0.95, 1.812461123), (10, 0.995, 3.169272673),
           (30, 0.975, 2.042272456), (100, 0.975, 1.983971519)]


def test_normal_quantiles(rec):
    """Квантили стандартного нормального распределения совпадают с табличными.

    Метод: P = 0,001; 0,9; 0,975; 0,995 (обе ветви алгоритма: центральная и хвост).
    Критерий: абсолютное отклонение не больше 1e-8.
    Зачем: квантиль z задаёт ширину полосы x̄ ± zσ для отклонений точек края.
    """
    for p, ref in ((0.001, -3.090232306), (0.9, 1.281551566), (0.975, 1.959963985), (0.995, 2.575829304)):
        e = abs(norm_ppf(p) - ref)
        assert rec(f"z при P = {p:g}", norm_ppf(p), f"{ref:.9f}", "", e <= 1e-8)


def test_student_quantiles(rec):
    """Квантили распределения Стьюдента совпадают с табличными при числе степеней свободы от 1 до 100.

    Метод: десять сочетаний ν и P, включая малые ν = 1…3, где нормальное приближение неприменимо.
    Критерий: относительное отклонение не больше 1e-8.
    Зачем: от квантиля t зависит ширина доверительного интервала и интервала предсказания;
    при N = 4…10 реализаций ошибка квантиля напрямую искажает интервал.
    """
    for nu, p, ref in T_TABLE:
        v = t_ppf(p, nu)
        assert rec(f"t({p:g}; ν = {nu})", v, f"{ref:.9f}", "", abs(v / ref - 1) <= 1e-8)


def test_student_cdf_properties(rec):
    """Функция распределения Стьюдента симметрична, равна ½ в нуле и обратна функции квантиля.

    Метод: F(0), F(t) + F(−t), F(t_ppf(P)) при ν = 1…12 и P = 0,9; 0,99.
    Критерий: отклонения не больше 1e-12.
    Зачем: квантиль уточняется методом Ньютона по этой функции; ошибка в ней сдвинет все интервалы.
    """
    e0 = max(abs(t_cdf(0.0, nu) - 0.5) for nu in range(1, 13))
    es = max(abs(t_cdf(1.7, nu) + t_cdf(-1.7, nu) - 1) for nu in range(1, 13))
    ei = max(abs(t_cdf(t_ppf(p, nu), nu) - p) for nu in range(1, 13) for p in (0.9, 0.99))
    assert rec("Наибольшее |F(0) − ½|", e0, "≤ 1e-12", "", e0 <= 1e-12)
    assert rec("Наибольшее |F(t) + F(−t) − 1|", es, "≤ 1e-12", "", es <= 1e-12)
    assert rec("Наибольшее |F(t_P) − P|", ei, "≤ 1e-12", "", ei <= 1e-12)


def test_interval_coverage_on_normal_samples(rec):
    """Доверительный интервал накрывает истинное среднее, а интервал предсказания — новое значение с заданной вероятностью.

    Метод: 4000 выборок по N = 6 из нормального распределения (μ = 120, σ = 2); для каждой — интервалы при P = 0,95;
    проверяется попадание μ в доверительный интервал и попадание нового независимого значения в интервал предсказания.
    Критерий: доля попаданий 0,95 ± 0,015 (≈ 4 стандартные ошибки доли).
    Зачем: проверяет, что интервалы, выдаваемые программой, имеют заявленную вероятность, в том числе при малом N.
    """
    rng = np.random.default_rng(3)
    ci = pi = 0
    for _ in range(4000):
        s = summary(rng.normal(120, 2, 6), 0.95)
        ci += s["ci"][0] <= 120 <= s["ci"][1]
        pi += s["pi"][0] <= rng.normal(120, 2) <= s["pi"][1]
    assert rec("Доля попаданий истинного среднего в ДИ", ci / 4000, "0,95 ± 0,015", "", abs(ci / 4000 - 0.95) <= 0.015)
    assert rec("Доля попаданий нового значения в интервал предсказания", pi / 4000, "0,95 ± 0,015", "", abs(pi / 4000 - 0.95) <= 0.015)


def test_interval_widths_scale(rec):
    """Доверительный интервал сужается как 1/√N, интервал предсказания стремится к ±z·σ.

    Метод: одна и та же выборка с СКО s, растянутая до N = 16 и N = 1024 повторением (СКО не меняется).
    Критерий: отношение ширин ДИ равно t₁₅/t₁₀₂₃·√(1024/16) до 1e-9; ширина интервала предсказания
    при N = 1024 отличается от 2·1,96·s меньше чем на 0,5 %.
    Зачем: объясняет пользователю, что увеличение N уточняет среднее, но не уменьшает разброс самих линий.
    """
    rng = np.random.default_rng(5)
    x = rng.normal(0, 1, 16)
    x = (x - x.mean()) / x.std(ddof=1)
    a, b = summary(x, 0.95), summary(np.tile(x, 64), 0.95)
    sb = b["sd"]
    r = (a["ci"][1] - a["ci"][0]) / (b["ci"][1] - b["ci"][0])
    ref = t_ppf(0.975, 15) / t_ppf(0.975, 1023) * 8 * a["sd"] / sb
    assert rec("Отношение ширин ДИ при N = 16 и N = 1024", r, f"{ref:.6f}", "", abs(r / ref - 1) <= 1e-9)
    w = (b["pi"][1] - b["pi"][0]) / (2 * 1.959963985 * sb)
    assert rec("Ширина интервала предсказания / (2·1,96·s)", w, "1 ± 0,005", "", abs(w - 1) <= 0.005)


def test_per_line_quantities(rec):
    """Величины одной линии рассчитываются по её краям точно.

    Метод: искусственные края: левый −62 + u(y), правый 61 + v(y) при номинале CD₀ = 120 нм; u, v — синусоиды
    с известной амплитудой.
    Критерий: CD = 123 нм; δ = (2 + 1)/2 = 1,5 нм; LER = 3·√(½(σ_u² + σ_v²)); LWR = 3·σ(v − u); всё до 1e-9.
    Зачем: эти значения по каждой реализации образуют выборку, по которой строятся интервалы.
    """
    y = np.arange(512)
    u, v = 1.5 * np.sin(2 * np.pi * y / 64), 2.0 * np.cos(2 * np.pi * y / 32)
    r = dict(xL=(-62 + u)[None], xR=(61 + v)[None])
    q = per_line(r, replace(Process(), CD=120.0))
    ler = 3 * np.sqrt(0.5 * (u.var() + v.var()))
    for name, got, ref in (("CD", q["cd"][0], 123.0), ("δ", q["dev"][0], 1.5), ("LER", q["ler"][0], ler),
                           ("LWR", q["lwr"][0], 3 * (v - u).std())):
        assert rec(name, got, f"{ref:.6f}", "нм", abs(got - ref) <= 1e-9)
    assert rec("Число точек краёв", q["points"].size, "1024", "", q["points"].size == 1024)


def test_parameter_perturbation(rec):
    """Случайные отклонения параметров процесса имеют заданные СКО и нулевое среднее.

    Метод: 4000 выборок отклонений при СКО дозы 2 %, фокуса 30 нм, температуры 0,5 °C, длины диффузии 5 %.
    Критерий: выборочные СКО в пределах ±5 % от заданных; средние — в пределах 4 стандартных ошибок.
    Зачем: от этого зависит вклад нестабильности процесса в разброс результата.
    """
    p = Process()
    rng = np.random.default_rng(11)
    var = dict(dose=2.0, focus=30.0, T_peb=0.5, L_D=5.0)
    q = [perturbed(p, var, rng) for _ in range(4000)]
    for key, sd, base in (("dose", p.dose * 0.02, p.dose), ("focus", 30.0, p.focus), ("T_peb", 0.5, p.T_peb),
                          ("L_D", p.L_D * 0.05, p.L_D)):
        x = np.array([getattr(o, key) for o in q])
        assert rec(f"СКО: {key}", x.std(), f"{sd:g} ± 5 %", "", abs(x.std() / sd - 1) <= 0.05)
        assert rec(f"Среднее: {key}", x.mean(), f"{base:g}", "", abs(x.mean() - base) <= 4 * sd / np.sqrt(4000))
    same = perturbed(p, {}, rng)
    assert rec("Без нестабильности параметры не меняются", same == p, "да", "", same == p)
