"""Двумерный фронт проявления: уравнение эйконала и положение краёв (lersim/process.py: arrival, edges)."""
import numpy as np
from lersim.process import arrival, edges


def test_uniform_resist_exact(rec):
    """В однородном резисте время прихода фронта точно равно расстоянию от центра пробела, делённому на скорость.

    Метод: поле 40 × 200 ячеек, R = 3 нм/с, шаги Δx = 1 нм, Δy = 2 нм; T сравнивается с (x + p/2)/R
    для левой половины периода и с (p/2 − x)/R для правой.
    Критерий: наибольшее отклонение не больше 1e-9 с.
    Зачем: плоский фронт — точное решение разностной схемы; ошибка означала бы сдвиг всех краёв.
    """
    ny, nx, dx = 40, 200, 1.0
    x = -nx / 2 + (np.arange(nx) + 0.5) * dx
    T = arrival(np.full((ny, nx), 3.0), dx, 2.0, 1e9)
    ref = np.minimum(x + nx / 2, nx / 2 - x) / 3.0
    e = float(np.abs(T - ref).max())
    assert rec("Наибольшее отклонение T от расстояния/R", e, "≤ 1e-9", "с", e <= 1e-9)


def test_layered_resist_reduces_to_path_integral(rec):
    """Если скорость меняется только поперёк линии, время прихода — интеграл ∫dx/R по прямому пути.

    Метод: R(x) от 0,05 до 80 нм/с (резкий профиль, как у края линии), одинаковый во всех строках;
    T сравнивается с суммой полушагов Δx/(2R) по пройденным ячейкам.
    Критерий: относительное отклонение не больше 1e-12; край, найденный по T, совпадает с аналитическим.
    Зачем: в пределе без шума двумерная модель обязана совпасть с одномерной (и с расчётом по средним концентрациям).
    """
    ny, nx, dx = 6, 300, 1.0
    x = -nx / 2 + (np.arange(nx) + 0.5) * dx
    R1 = 0.05 + 80 / (1 + np.exp((60 - np.abs(x)) / 4))
    R = np.tile(R1, (ny, 1))
    T = arrival(R, dx, 1.0, 1e9)
    f = 1 / R1
    ref = np.empty(nx // 2)
    ref[0] = 0.5 * dx * f[0]
    for i in range(1, nx // 2):
        ref[i] = ref[i - 1] + 0.5 * dx * (f[i - 1] + f[i])
    e = float(np.abs(T[:, :nx // 2] / ref - 1).max())
    assert rec("Относительное отклонение T от ∫dx/R", e, "≤ 1e-12", "", e <= 1e-12)
    t_dev = 20.0
    xl = edges(T, R, x, t_dev)[0]
    # Аналитический край для кусочно-постоянной скорости: интеграл до места, где время равно t_dev.
    i = np.searchsorted(ref, t_dev) - 1
    e = t_dev - ref[i]
    exact = x[i] + (e * R1[i] if e < 0.5 * dx * f[i] else 0.5 * dx + (e - 0.5 * dx * f[i]) * R1[i + 1])
    assert rec("Положение края", float(xl[0]), f"{exact:.6f}", "нм", np.allclose(xl, exact, atol=1e-9))


def test_front_bypasses_insoluble_cell(rec):
    """Нерастворимая ячейка не останавливает фронт: проявитель обходит её по соседним строкам.

    Метод: однородный резист R = 2 нм/с; в одной строке на пути фронта ячейка с R = 10⁻⁶ нм/с; t_dev = 40 с.
    Критерий: край в этой строке отстоит от края соседних строк меньше чем на 2Δx; без бокового обхода
    (одномерная модель) фронт остановился бы перед ячейкой, на 50 нм раньше.
    Зачем: именно боковое проявление вокруг медленных участков отличает двумерную модель от построчной
    и убирает завышение шероховатости при малой длине диффузии.
    """
    ny, nx, dx = 21, 300, 1.0
    x = -nx / 2 + (np.arange(nx) + 0.5) * dx
    R = np.full((ny, nx), 2.0)
    R[10, 30] = 1e-6
    T = arrival(R, dx, 1.0, 1e9)
    xl = edges(T, R, x, 40.0)[0]
    gap = float(abs(xl[10] - xl[0]))
    assert rec("Смещение края в строке с нерастворимой ячейкой", gap, "< 2", "нм", gap < 2 * dx)
    assert rec("Время прихода за препятствием конечно", float(T[10, 31]), "< 20", "с", T[10, 31] < 20)


def test_lateral_paths_only_shorten(rec):
    """Двумерное время прихода не больше одномерного по той же строке и не меньше пути с наибольшей скоростью.

    Метод: случайное поле скоростей (логнормальное, разброс в 100 раз), 30 × 120 ячеек.
    Критерий: T ≤ ∫dx/R по своей строке во всех ячейках; T ≥ расстояние / R_max.
    Зачем: принцип Ферма — фронт выбирает самый быстрый путь; нарушение означало бы ошибку схемы.
    """
    rng = np.random.default_rng(4)
    ny, nx, dx = 30, 120, 1.0
    R = np.exp(rng.normal(0, 1.2, (ny, nx)))
    T = arrival(R, dx, 1.0, 1e12)
    f = 1 / R
    one = np.empty_like(T)
    one[:, 0] = 0.5 * dx * f[:, 0]
    for i in range(1, nx // 2):
        one[:, i] = one[:, i - 1] + 0.5 * dx * (f[:, i - 1] + f[:, i])
    upper = bool(np.all(T[:, :nx // 2] <= one[:, :nx // 2] * (1 + 1e-12)))
    x = (np.arange(nx // 2) + 0.5) * dx
    lower = bool(np.all(T[:, :nx // 2] >= x / R.max() * (1 - 1e-12)))
    assert rec("T не больше одномерного пути по строке", upper, "да", "", upper)
    assert rec("T не меньше расстояния / R_max", lower, "да", "", lower)
