"""Оптическое изображение, экспонирование, постэкспозиционная сушка и проявление (lersim/process.py)."""
from dataclasses import replace
import numpy as np
import pytest
from lersim.core import development_rate
from lersim.process import (Process, aerial_image, expose, peb, develop, diffusion_kernels, grid,
                            mean_field, simulate)

x = np.linspace(-150, 150, 301)


def two_beam(x, CD, pitch, wl, focus):
    """Когерентное освещение, проходят только порядки 0 и ±1: точное выражение."""
    m0, m1 = 1 - CD / pitch, -(CD / pitch) * np.sinc(CD / pitch)
    phi = focus * 2 * np.pi * (np.sqrt(wl**-2 - pitch**-2) - 1 / wl)
    c = np.cos(2 * np.pi * x / pitch)
    return m0**2 + 4 * m1**2 * c**2 + 4 * m0 * m1 * c * np.cos(phi)


def test_open_frame_is_one(rec):
    """Открытое поле без линии даёт интенсивность ровно 1.

    Метод: маска с нулевой шириной линии, частично когерентный источник σ = 0,6.
    Критерий: интенсивность во всех точках равна 1 с точностью 1e-8.
    Зачем: проверяет нормировку изображения, от которой зависит связь дозы с шириной линии.
    """
    I = aerial_image(x, 0, 300, 193, 0.75, 0.6, 0)
    assert rec("Наибольшее отклонение от 1", float(np.abs(I - 1).max()), "≤ 1e-8", "", np.abs(I - 1).max() <= 1e-8)


@pytest.mark.parametrize("focus", [0.0, 80.0, 250.0])
def test_coherent_two_beam_image_is_exact(rec, focus):
    """Когерентное изображение из трёх порядков совпадает с точной формулой, в том числе в расфокусе.

    Метод: шаг 300 нм, NA 0,75, λ 193 нм: зрачок пропускает порядки 0 и ±1. Точная интенсивность
    I = m0² + 4m1²cos² + 4m0m1·cos(2πx/p)·cos φ, где φ — фазовый набег порядка ±1 при расфокусе.
    Критерий: максимальное отклонение не больше 1e-12.
    Зачем: проверяет оптический расчёт — дифракцию на маске, зрачок и дефокус — без приближений.
    """
    assert rec("Через зрачок проходят только порядки 0 и ±1", 1 / 300 < 0.75 / 193 < 2 / 300, "да", "", 1 / 300 < 0.75 / 193 < 2 / 300)
    e = np.abs(aerial_image(x, 120, 300, 193, 0.75, 0.0, focus) - two_beam(x, 120, 300, 193, focus)).max()
    assert rec("Наибольшее отклонение от точной формулы", e, "≤ 1e-12", "", e <= 1e-12)


def test_image_symmetry_in_x_and_focus(rec):
    """Изображение симметрично относительно центра линии и знака расфокусировки.

    Метод: изображение при фокусе +40 нм сравнивается с зеркальным по x и с изображением при −40 нм.
    Критерий: отклонения не больше 1e-12.
    Зачем: без аберраций оба свойства обязаны выполняться; нарушение означает ошибку фаз.
    """
    I = aerial_image(x, 120, 300, 193, 0.75, 0.6, 40)
    a = np.abs(I - I[::-1]).max()
    b = np.abs(I - aerial_image(x, 120, 300, 193, 0.75, 0.6, -40)).max()
    assert rec("Асимметрия по x", a, "≤ 1e-12", "", a <= 1e-12)
    assert rec("Различие при +40 и −40 нм", b, "≤ 1e-12", "", b <= 1e-12)


def test_contrast_falls_with_defocus(rec):
    """Контраст изображения строго падает с расфокусировкой.

    Метод: контраст (Imax − Imin)/(Imax + Imin) при фокусе 0, 50, 100, 150, 200 нм.
    Критерий: каждое следующее значение меньше предыдущего.
    Зачем: базовое свойство оптики; от контраста зависит шероховатость края.
    """
    c = []
    for f in (0, 50, 100, 150, 200):
        I = aerial_image(x, 120, 300, 193, 0.75, 0.6, f)
        c.append((I.max() - I.min()) / (I.max() + I.min()))
        rec(f"Контраст при фокусе {f} нм", c[-1])
    assert rec("Контраст строго убывает", all(a > b for a, b in zip(c, c[1:])), "да", "", all(a > b for a, b in zip(c, c[1:])))


def test_exposure_statistics(rec, p):
    """Статистика экспонирования: число кислот и молекул тушителя в ячейке.

    Метод: 4000 строк ячеек; среднее число кислот в каждом столбце сравнивается с c_PAG·V·P(x),
    где P = 1 − exp(−C·доза·I); для тушителя проверяется равенство дисперсии и среднего (Пуассон).
    Критерий: отклонение среднего не больше 5 стандартных ошибок в любом столбце; среднее и дисперсия
    тушителя совпадают с c_Q·V в пределах 1 % и 3 %.
    Зачем: дробовой шум химии — первоисточник LER в модели; его статистика должна быть точной.
    """
    I = aerial_image(grid(p), p.CD, p.pitch, p.wl, p.NA, p.sigma_s, p.focus)
    cH, cQ = expose(I, p, np.random.default_rng(3), 4000)
    V = p.dx * p.dy * p.h_eff
    NH, NQ = cH * V, cQ * V
    mu = p.c_pag * V * -np.expm1(-p.C_g * p.dose * I)
    z = np.abs((NH.mean(0) - mu) / (np.sqrt(mu) / np.sqrt(NH.shape[0]))).max()
    assert rec("Наибольшее отклонение среднего числа кислот", z, "< 5", "станд. ошибок", z < 5)
    assert rec("Среднее число молекул тушителя", NQ.mean(), f"{p.c_q * V:g} ± 1 %", "", np.isclose(NQ.mean(), p.c_q * V, rtol=0.01))
    assert rec("Дисперсия числа молекул тушителя", NQ.var(), f"{p.c_q * V:g} ± 3 %", "", np.isclose(NQ.var(), p.c_q * V, rtol=0.03))


def test_diffusion_length_parameter(rec):
    """Длина диффузии задаёт D при опорных условиях и масштабируется как √t.

    Метод: L_D = 20 нм при 105 °C и 60 с; PEB 120 с при той же температуре.
    Критерий: D_ref = L²/(2·t_ref) = 3,333 нм²/с; фактическая длина 20·√2 = 28,28 нм.
    Зачем: длина диффузии — входной параметр программы; пересчёт должен быть точным.
    """
    p = Process(L_D=20.0)
    assert rec("Коэффициент диффузии при опорных условиях", p.D_ref, "3,333", "нм²/с", np.isclose(p.D_ref, 400 / 120))
    r = simulate(replace(p, L=600.0, t_peb=120.0), 1)
    assert rec("Фактическая длина диффузии при 120 с", r["L_diff"], "28,28", "нм", np.isclose(r["L_diff"], 20 * np.sqrt(2)))


def test_old_parameter_files_are_migrated(rec):
    """Файлы параметров прежней версии загружаются.

    Метод: словарь с прежним полем D_ref = 2 нм²/с, дозой 30 и неизвестным полем.
    Критерий: длина диффузии √(2·2·60) = 15,49 нм, доза сохранена, неизвестное поле проигнорировано.
    Зачем: сохранённые ранее параметры моделирования должны открываться в новой версии.
    """
    p = Process.from_dict({"D_ref": 2.0, "dose": 30.0, "unknown": 1})
    assert rec("Длина диффузии из D_ref", p.L_D, "15,49", "нм", np.isclose(p.L_D, np.sqrt(240.0)))
    assert rec("Доза", p.dose, "30", "мДж/см²", p.dose == 30.0)


def test_zero_diffusion_kernel_is_identity(rec):
    """При нулевой диффузии ядро — единица, поле не меняется.

    Метод: ядра для D = 0.
    Критерий: оба ядра состоят из одного элемента, равного 1.
    Зачем: защита от деления на ноль и размывания при выключенной диффузии.
    """
    kx, ky = diffusion_kernels(Process(), 0.0, 2.0)
    assert rec("Ядро по x", str(kx.tolist()), "[1.0]", "", kx.tolist() == [1.0])
    assert rec("Ядро по y", str(ky.tolist()), "[1.0]", "", ky.tolist() == [1.0])


def test_peb_uniform_field_exact(rec):
    """Реакция в однородном поле совпадает с точным решением.

    Метод: c_H = 0,05, c_Q = 0,02 нм⁻³ во всех ячейках; однородное поле диффузия не меняет.
    Точное решение: d = 1 − exp(−k_d·(c_H − c_Q)·t).
    Критерий: относительное отклонение не больше 1e-12; k_d при опорной температуре равна k_ref.
    Зачем: проверяет нейтрализацию и накопление депротекции в схеме расщепления по времени.
    """
    p = Process()
    d, D, kd = peb(np.full((40, 30), 0.05), np.full((40, 30), 0.02), p)
    exact = -np.expm1(-kd * 0.03 * p.t_peb)
    assert rec("Константа депротекции", kd, f"{p.kd_ref:g}", "нм³/с", kd == p.kd_ref)
    e = float(np.abs(d / exact - 1).max())
    assert rec("Отклонение от точного решения", e, "≤ 1e-12", "", e <= 1e-12)


def test_diffusion_kernel_conserves_acid_and_matches_spectral(rec):
    """Ядро диффузии сохраняет кислоту и совпадает с точным спектральным решением.

    Метод: ядра для D = 2 нм²/с, шаг 2 с; передаточная функция ядра против exp(−D(2πf)²Δt) на сетках x и y.
    Критерий: сумма весов 1, ядро симметрично, расхождение передаточной функции < 1e-4, длина ядра < 31.
    Зачем: ядро C++ использует именно эти веса; ошибка дала бы потерю кислоты или неверное сглаживание.
    """
    p = Process()
    for axis, h, n, k in zip("xy", (p.dx, p.dy), (300, 600), diffusion_kernels(p, 2.0, 2.0)):
        f = np.fft.rfftfreq(n, h)
        r = k.size // 2
        H = np.array([np.sum(k * np.cos(2 * np.pi * fi * np.arange(-r, r + 1) * h)) for fi in f])
        e = np.abs(H - np.exp(-2 * (2 * np.pi * f) ** 2 * 2.0)).max()
        assert rec(f"Сумма весов ядра по {axis}", k.sum(), "1", "", np.isclose(k.sum(), 1.0))
        assert rec(f"Симметрия ядра по {axis}", bool(np.allclose(k, k[::-1])), "да", "", np.allclose(k, k[::-1]))
        assert rec(f"Расхождение с точным решением по {axis}", e, "< 1e-4", "", e < 1e-4)
    n = diffusion_kernels(p, 2.0, 2.0)[0].size
    assert rec("Длина ядра по x (обрезка 4,5σ)", n, "< 31", "узлов", n < 31)


def test_development_front_in_uniform_resist(rec):
    """Фронт проявления в однородном резисте.

    Метод: доля снятой защиты 0,3 всюду; скорость R постоянна, фронт за t_dev проходит R·t_dev.
    Затем резист с полностью снятой защитой — линия должна раствориться.
    Критерий: края на расстоянии R·t_dev от центров пробелов (точность 1e-8); во втором случае — разрыв.
    Зачем: проверяет расчёт времени прихода фронта и признак разрыва линии.
    """
    p = Process()
    xg = grid(p)
    R = development_rate(0.3, p.R_min, p.R_max, p.a_dev, p.n_dev)
    l, r, lost = develop(np.full((5, xg.size), 0.3), xg, p)
    assert rec("Путь фронта R·t_dev", R * p.t_dev, f"0 … {p.pitch / 2:g}", "нм", 0 < R * p.t_dev < p.pitch / 2)
    assert rec("Левый край", float(l[0]), f"{-p.pitch / 2 + R * p.t_dev:.3f}", "нм", np.allclose(l, -p.pitch / 2 + R * p.t_dev))
    assert rec("Правый край", float(r[0]), f"{p.pitch / 2 - R * p.t_dev:.3f}", "нм", np.allclose(r, p.pitch / 2 - R * p.t_dev))
    assert rec("Разрывов при частичной депротекции", int(lost.sum()), "0", "", not lost.any())
    lost = develop(np.ones((5, xg.size)), xg, p)[2]
    assert rec("Разрывов при полной депротекции", int(lost.sum()), "5 из 5", "", lost.all())


def test_mean_field_is_noise_free_limit(rec, p):
    """В пределе без дробового шума стохастический расчёт совпадает со средне-полевым.

    Метод: эффективная толщина 10⁵ нм вместо 50 — объём ячейки в 2000 раз больше, шум в √2000 ≈ 45 раз меньше.
    Критерий: ширина отличается от средне-полевой меньше чем на 0,1 нм; LER < 0,3 нм.
    Зачем: связывает две реализации модели — стохастическую и детерминированную (окно процесса).
    """
    r = simulate(replace(p, h_eff=1e5), 1, "numpy")
    mf = mean_field(p)[0]
    assert rec("Ширина: стохастическая − средне-полевая", r["m"]["CD"] - mf, "|…| < 0,1", "нм", abs(r["m"]["CD"] - mf) < 0.1)
    assert rec("Шероховатость левого края", r["m"]["LER_L"], "< 0,3", "нм", r["m"]["LER_L"] < 0.3)


def test_numpy_engine_is_reproducible(rec, p):
    """Эталонное ядро NumPy воспроизводимо при том же начальном значении генератора.

    Метод: два расчёта с одинаковыми параметрами и генератором.
    Критерий: контуры краёв совпадают побитово.
    Зачем: воспроизводимость — условие проверки и сравнения результатов.
    """
    a, b = simulate(p, 2, "numpy"), simulate(p, 2, "numpy")
    same = np.array_equal(a["xL"], b["xL"]) and np.array_equal(a["xR"], b["xR"])
    assert rec("Контуры совпадают побитово", same, "да", "", same)
