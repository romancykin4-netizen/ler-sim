"""Расчёт окна процесса на синтетической карте с аналитическим решением (lersim/sweep.py)."""
import numpy as np
from lersim.sweep import dose_to_size, latitude

# CD(доза, фокус) = 200 − 3·E + k·f²: доза номинального размера E0 = (100 + k f²)/3,
# энергетическая широта EL при ±10 % от 100 нм: EL = 100·(20/3)/E0 = 2000/(100 + k f²) %.
k = 1e-3
doses = np.linspace(10, 120, 111)
focuses = np.arange(-400, 401, 50.0)
CD = 200 - 3 * doses[:, None] + k * focuses[None, :] ** 2


def test_dose_to_size_exact(rec):
    """Доза номинального размера на синтетической карте совпадает с аналитической.

    Метод: карта ширины CD = 200 − 3·E + 10⁻³·f²; доза, дающая 100 нм, равна E0 = (100 + 10⁻³·f²)/3.
    Критерий: совпадение во всех 17 точках фокуса до 1e-8.
    Зачем: доза номинального размера выводится в таблицу результатов.
    """
    E0 = dose_to_size(CD, doses, 100.0)
    e = np.abs(E0 - (100 + k * focuses**2) / 3).max()
    rec("Доза номинального размера при фокусе 0", float(E0[8]), "33,33", "мДж/см²")
    assert rec("Наибольшее отклонение от формулы", e, "≤ 1e-8", "мДж/см²", e <= 1e-8)


def test_dose_to_size_outside_grid_is_nan(rec):
    """Если нужная ширина недостижима в диапазоне доз, результат помечается как отсутствующий.

    Метод: запрос ширины 1000 нм, которой нет на карте.
    Критерий: все значения — «нет данных» (NaN), а не экстраполяция.
    Зачем: программа не должна выдавать выдуманную дозу за пределами расчёта.
    """
    v = dose_to_size(CD, doses, 1000.0)
    assert rec("Точек с «нет данных»", int(np.isnan(v).sum()), f"{v.size} из {v.size}", "", np.isnan(v).all())


def test_latitude_and_dof_exact(rec):
    """Энергетическая широта EL и глубина фокуса на синтетической карте совпадают с аналитическими.

    Метод: та же карта; энергетическая широта EL при допуске ±10 %: EL = 2000/(100 + 10⁻³·f²) %;
    глубина фокуса — диапазон фокусов, где EL ≥ 10 %: |f| ≤ 316 нм, на сетке с шагом 50 нм это 600 нм.
    Критерий: EL совпадает во всех точках до 1e-8; глубина фокуса 600 нм.
    Зачем: эти величины выводятся в таблицу результатов окна процесса.
    """
    E0, EL, dof = latitude(CD, doses, focuses, 100.0, tol=0.1, el_min=10.0)
    rec("Энергетическая широта EL при фокусе 0", float(EL[8]), "20", "%")
    e = np.abs(EL - 2000 / (100 + k * focuses**2)).max()
    assert rec("Наибольшее отклонение энергетической широты от формулы", e, "≤ 1e-8", "%", e <= 1e-8)
    assert rec("Глубина фокуса DOF", dof, "600", "нм", dof == 600.0)
